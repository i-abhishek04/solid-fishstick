#include<stdio.h>
#include<limits.h>

int main(){
    printf("The value of signed char max is %d\n", CHAR_MAX);    
    printf("The value of signed char min is %d\n", CHAR_MIN);    
    printf("The value of unsigned char max is %d\n", UCHAR_MAX);    
    printf("The value of signed short max is %d\n", SHRT_MAX);    
    printf("The value of signed short min is %d\n", SHRT_MIN);    
    printf("The value of unsigned short max is %d\n", USHRT_MAX);    
    printf("The value of unsigned int max is %d\n", INT_MAX);    
    printf("The value of unsigned int max is %u\n", UINT_MAX);    
    return 0;
}